async function menu(page: Page, name: string, item: string) {
  await page.getByRole('menubar').getByRole('menuitem', { name, exact: true }).click()
  await page.locator('.menu-panel').getByRole('menuitem', { name: item, exact: true }).click()
}

async function create(page: Page) {
  await page.addInitScript(() => localStorage.setItem('ofimeo:language', 'en'))
  await page.goto(`/${RELAYS}#new=diagram`)
  await page.locator('.diagram-canvas svg').first().waitFor()
  await menu(page, 'Insert', 'Gantt chart')
  await expect(page.locator('.gantt-workspace')).toBeVisible()
  await expect(page.locator('.gantt-tasks tbody tr')).toHaveCount(5)
}

async function exportFile(page: Page, name: string) {
  await page.getByRole('menubar').getByRole('menuitem', { name: 'File', exact: true }).click()
  await page.getByText('Download as', { exact: true }).hover()
  const download = page.waitForEvent('download')
  await page.getByRole('menuitem', { name, exact: true }).click()
  return readFile(await (await download).path())
}

test('Gantt tasks recalculate dependencies, reject cycles and survive reload', async ({ page }) => {
  const errors = trackErrors(page)
  await create(page)
  await page.getByRole('button', { name: 'Define the project', exact: true }).click()
  await page.getByLabel('Earliest start date', { exact: true }).fill('2030-03-28')
  await page.getByLabel('Duration (calendar days)', { exact: true }).fill('4')
  await page.getByLabel('Responsible person', { exact: true }).fill('Ana')
  await page.getByLabel('Progress (%)', { exact: true }).fill('50')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const rows = page.locator('.gantt-tasks tbody tr')
  await expect(rows.nth(0).locator('time').nth(1)).toHaveAttribute('datetime', '2030-03-31')
  await expect(rows.nth(1).locator('time').first()).toHaveAttribute('datetime', '2030-04-01')
  await expect(rows.nth(0)).toContainText('Ana')
  await expect(rows.nth(0)).toContainText('50%')
  await page.getByRole('button', { name: 'Define the project', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Final delivery', exact: true }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('dialog [role="alert"]')).toContainText('cycle')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.reload()
  await expect(page.locator('.gantt-workspace')).toBeVisible()
  await expect(rows.nth(0)).toContainText('Ana')
  await expect(rows.nth(1).locator('time').first()).toHaveAttribute('datetime', '2030-04-01')
  expect(errors).toEqual([])
})

test('Gantt bars move and resize with keyboard, undo and pointer gestures', async ({ page }) => {
  await create(page)
  const bar = page.locator('.gantt-bar').first()
  const row = page.locator('.gantt-tasks tbody tr').first()
  const original = await row.locator('time').first().getAttribute('datetime')
  await bar.focus()
  await page.keyboard.press('ArrowRight')
  await expect(row.locator('time').first()).not.toHaveAttribute('datetime', original!)
  await page.locator('.gantt-toolbar').getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(row.locator('time').first()).toHaveAttribute('datetime', original!)
  const before = await bar.locator('.gantt-bar-shape').getAttribute('width')
  await bar.focus()
  await page.keyboard.press('Shift+ArrowRight')
  await expect(bar.locator('.gantt-bar-shape')).not.toHaveAttribute('width', before!)
  const shape = await bar.locator('.gantt-bar-shape').boundingBox()
  await page.mouse.move(shape!.x + 8, shape!.y + 11)
  await page.mouse.down()
  await page.mouse.move(shape!.x + 44, shape!.y + 11, { steps: 5 })
  await page.mouse.up()
  await expect(row.locator('time').first()).not.toHaveAttribute('datetime', original!)
})

test('Gantt native files preserve tasks, duplicates are independent, PDF and images export', async ({ page }) => {
  const errors = trackErrors(page)
  await create(page)
  const xml = await exportFile(page, 'draw.io diagram (.drawio)')
  expect(xml.toString()).toContain('ofimeoGantt=')
  expect(xml.toString()).toContain('Define the project')
  await menu(page, 'Page', 'Duplicate page')
  await expect(page.locator('.page-tab')).toHaveCount(3)
  await page.getByRole('button', { name: 'Define the project', exact: true }).click()
  await page.getByLabel('Task', { exact: true }).fill('Independent copy')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('tab', { name: 'Gantt chart', exact: true }).click()
  await expect(page.locator('.gantt-tasks')).toContainText('Define the project')
  await expect(page.locator('.gantt-tasks')).not.toContainText('Independent copy')
  const pdf = await exportFile(page, 'PDF document (all pages)')
  expect(pdf.subarray(0, 5).toString()).toBe('%PDF-')
  const png = await exportFile(page, 'PNG image (current page)')
  expect(png.subarray(1, 4).toString()).toBe('PNG')
  const svg = await exportFile(page, 'SVG image (current page)')
  expect(svg.toString()).toContain('Research')
  await page.goto(`/${RELAYS}`)
  const chooser = page.waitForEvent('filechooser')
  await page.locator('.home-open').first().click()
  await (await chooser).setFiles({ name: 'project.drawio', mimeType: 'application/xml', buffer: xml })
  // Reimport starts on the original blank page; select the saved Gantt page.
  await page.getByRole('tab', { name: 'Gantt chart', exact: true }).click()
  await expect(page.locator('.gantt-tasks tbody tr')).toHaveCount(5)
  await page.getByRole('button', { name: 'Research', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Define the project', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(errors).toEqual([])
})

