test('Gantt edits synchronize between peers and a view link cannot edit', async ({ browser }) => {
  const firstContext = await browser.newContext({ locale: 'en-US' })
  const secondContext = await browser.newContext({ locale: 'en-US' })
  try {
    const a = await firstContext.newPage()
    const b = await secondContext.newPage()
    await create(a)
    test.skip(!await a.evaluate(() => typeof RTCPeerConnection !== 'undefined'), 'This browser build has no WebRTC; local Gantt editing is covered separately.')
    await b.goto(a.url())
    await b.getByRole('tab').filter({ hasText: 'Gantt chart' }).click({ timeout: 60_000 })
    await expect(b.locator('.gantt-workspace')).toBeVisible({ timeout: 60_000 })
    await a.getByRole('button', { name: 'Research', exact: true }).click()
    await a.getByLabel('Responsible person', { exact: true }).fill('Alex')
    await a.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(b.locator('.gantt-tasks')).toContainText('Alex', { timeout: 60_000 })
    await a.locator('#btn-share').click()
    const dialog = a.locator('dialog.dlg')
    await dialog.getByRole('tab', { name: 'Can view', exact: true }).click()
    const viewLink = await dialog.locator('input.field').inputValue()
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    const viewerContext = await browser.newContext({ locale: 'en-US' })
    try {
      const viewer = await viewerContext.newPage()
      await viewer.goto(viewLink)
      await viewer.getByRole('tab').filter({ hasText: 'Gantt chart' }).click({ timeout: 60_000 })
      await expect(viewer.locator('.gantt-workspace')).toBeVisible({ timeout: 60_000 })
      await expect(viewer.locator('.gantt-toolbar').getByRole('button', { name: 'Add task', exact: true })).toBeHidden()
      await expect(viewer.locator('.gantt-tasks button')).toHaveCount(0)
      await expect(viewer.locator('.gantt-bar[tabindex]')).toHaveCount(0)
      await expect(viewer.locator('.gantt-tasks')).toContainText('Alex')
    } finally { await viewerContext.close() }
  } finally { await firstContext.close(); await secondContext.close() }
})

test('Gantt WebMCP exposes task operations and guards the generated shapes', async ({ page }) => {
  const errors = trackErrors(page)
  await page.addInitScript(ENABLED)
  await create(page)
  await expect.poll(() => toolNames(page)).toContain('get_gantt')
  expect(await toolNames(page)).not.toContain('set_label')
  const result = await call(page, 'get_gantt')
  expect(result.error).toBe(false)
  const tasks = (result.data as { tasks: { id: string; name: string }[] }).tasks
  expect(tasks).toHaveLength(5)
  expect((await call(page, 'update_gantt_task', { id: tasks[0].id, owner: 'Casey' })).error).toBe(false)
  await expect(page.locator('.gantt-tasks')).toContainText('Casey')
  expect((await call(page, 'update_gantt_task', { id: tasks[0].id, dependencies: [tasks[4].id] })).error).toBe(true)
  expect((await call(page, 'get_gantt')).error).toBe(false)
  expect(errors).toEqual([])
})
